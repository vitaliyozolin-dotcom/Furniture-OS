import { expect, test } from '@playwright/test';

test('registers, constructs, saves and publishes an immutable cabinet request', async ({ page, context }, testInfo) => {
  const email = `cabinet-${Date.now()}-${testInfo.project.name}@example.test`;
  const title = `Шкаф ${testInfo.project.name}`;
  await page.goto('/');
  await expect(page.getByRole('link', { name: 'Войти', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Регистрация', exact: true })).toBeVisible();
  await page.getByRole('link', { name: /Новый шкаф/ }).click();
  await expect(page.getByRole('heading', { name: 'Конструктор шкафа' })).toBeVisible();
  await page.getByLabel('Ширина, мм', { exact: true }).fill('2700');
  await page.getByLabel('Высота, мм', { exact: true }).fill('2500');
  await page.getByLabel('Глубина, мм', { exact: true }).fill('650');
  await page.getByRole('button', { name: '2. Наполнение', exact: true }).click();
  await page.getByLabel('Тип секции 1', { exact: true }).selectOption('drawers');
  await page.getByLabel('Полки, секция 1', { exact: true }).fill('2');
  await page.getByLabel('Ящики, секция 1', { exact: true }).fill('3');
  await page.getByRole('button', { name: 'Добавить секцию', exact: true }).click();
  await page.getByRole('button', { name: 'Удалить секцию 4', exact: true }).click();
  await page.getByRole('button', { name: '3. Материалы', exact: true }).click();
  await page.getByLabel('Корпус', { exact: true }).selectOption('graphite');
  await page.getByLabel('Фасады', { exact: true }).selectOption('mdf');
  await page.getByRole('button', { name: 'Показать фасады', exact: true }).click();
  await expect(page.locator('[data-door]')).toHaveCount(3);
  await page.getByRole('link', { name: 'Войти и сохранить шкаф' }).click();
  await page.getByRole('link', { name: 'Создать новый аккаунт' }).click();
  await page.getByLabel('Имя', { exact: true }).fill('Покупатель');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Пароль', { exact: true }).fill('CabinetTest123!');
  await page.getByRole('button', { name: 'Зарегистрироваться', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Конструктор шкафа' })).toBeVisible();
  await expect(page.getByLabel('Ширина, мм', { exact: true })).toHaveValue('2700');
  await page.getByLabel('Название проекта', { exact: true }).fill(title);
  await page.getByRole('button', { name: 'Сохранить проект', exact: true }).click();
  await expect(page).toHaveURL(/\/constructor\/[a-f0-9]{32}$/);
  const privateUrl = page.url();
  await page.reload();
  await expect(page.getByLabel('Ширина, мм', { exact: true })).toHaveValue('2700');
  await page.getByRole('button', { name: '4. Публикация', exact: true }).click();
  await page.getByLabel('Город', { exact: true }).fill('Москва');
  await page.getByLabel('Пожелания', { exact: true }).fill('Нужен шкаф для спальни');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Опубликовать заявку', exact: true }).click();
  await expect(page).toHaveURL(/\/p\/[a-f0-9]{32}$/);
  const publicUrl = page.url();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await expect(page.getByLabel('Ссылка на заявку')).toHaveValue(publicUrl);
  await page.goto(privateUrl);
  await page.getByLabel('Ширина, мм', { exact: true }).fill('2800');
  await page.getByRole('button', { name: 'Сохранить проект', exact: true }).click();
  await expect(page.getByText('Проект сохранён', { exact: true })).toBeVisible();
  await page.goto(publicUrl);
  await expect(page.getByRole('img', { name: /2700 × 2500 × 650/ })).toBeVisible();
  const cookie = (await context.cookies()).find((item) => item.name === 'FURNITURE_SESSION');
  expect(cookie?.httpOnly).toBe(true); expect(cookie?.sameSite).toBe('Lax');
  await page.getByRole('button', { name: 'Выйти', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Войти', exact: true })).toBeVisible();
  await page.goto(privateUrl);
  await expect(page.getByRole('heading', { name: 'Войдите, чтобы открыть проект' })).toBeVisible();
  await page.goto(publicUrl);
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Пароль', { exact: true }).fill('CabinetTest123!');
  await page.getByRole('button', { name: 'Войти в аккаунт', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Открыть проект', exact: true }).click();
  await page.getByRole('button', { name: '4. Публикация', exact: true }).click();
  await page.getByRole('button', { name: 'Снять публикацию', exact: true }).click();
  await expect(page.getByText('Публикация снята')).toBeVisible();
  await page.goto(publicUrl);
  await expect(page.getByRole('heading', { name: 'Заявка недоступна' })).toBeVisible();
});
